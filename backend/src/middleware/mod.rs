//! 自定义中间件。
//!
//! 存放框架未内建、且与业务域无关的 HTTP 请求前后处理逻辑。框架已由 `config.toml`
//! 驱动装配了安全头 / CORS / 请求日志 / 认证 / 权限 / 限流 / 压缩等标准中间件，
//! 本目录只补充业务特有需求（如操作日志落库）。
//!
//! 装配方式：在 [`crate::run`] 中通过 `App::layer_from_fn` 注册，
//! 该层在框架默认中间件链与 404 / 静态资源兜底**之后**应用，因此位于最外层
//! （能观测到 401 / 403 / 429 与真实端到端耗时）。
//!
//! | 中间件 | 职责 | 交付阶段 |
//! |--------|------|----------|
//! | [`operation_log`] | 记录写操作（方法 / 路径 / 操作人 / 耗时 / 结果）到 `operation_logs` | P4 |

