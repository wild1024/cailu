//! 工作台概览（首页数据聚合）。
//!
//! 把散落在 `auth_logs` / `sys_user` / `sys_job` 中的统计口径收敛到一处，首页只需
//! 一次请求即可拿到指标卡片与趋势图数据：
//!
//! | 文件 | 职责 |
//! |------|------|
//! | [`dto`] | 响应契约（指标卡片、趋势图、聚合结果） |
//! | [`model`] | SQL 聚合与卡片装配（数据访问集中在 model.rs） |
//! | [`handler`] | 路由 `GET /support/dashboard/overview` |
//!
//! 不设 service 层：接口只有一次编排，业务逻辑全在 [`model`] 内。
//!
//! # 设计约束
//!
//! - **不新增统计表**：概览数据全部由既有日志表聚合而来，避免「统计表与业务表漂移」；
//! - **只读旁路**：接口无写操作，缓存（在线会话）异常时降级为 0 而不报 500；
//! - **口径随响应下发**：每张卡片的 `tip` 说明统计范围，前端不再硬编码业务口径。

pub mod dto;
pub mod handler;
pub mod model;
